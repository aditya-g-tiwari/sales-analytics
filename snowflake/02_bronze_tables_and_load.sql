        $1:raw_data,
        $1:insert_date::TIMESTAMP_NTZ
    FROM @S3_RAW_STAGE/custom_activities/
)
FILE_FORMAT = (
    FORMAT_NAME = 'RAW_JSON_FORMAT'
)
PATTERN = '.*part-.*[.]json'
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO CLOSE_CRM_USERS_RAW
(
    RAW_DATA,
    INSERT_DATE
)
FROM
(
    SELECT
        $1:raw_data,
        $1:insert_date::TIMESTAMP_NTZ
    FROM @S3_RAW_STAGE/close_crm_users/
)
FILE_FORMAT = (
    FORMAT_NAME = 'RAW_JSON_FORMAT'
)
PATTERN = '.*part-.*[.]json'
ON_ERROR = 'ABORT_STATEMENT';
